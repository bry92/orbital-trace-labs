import type { Artifact } from "../export/serialize";

export function downloadText(name: string, content: string, mime: string): void {
  const blob = new Blob([content], { type: `${mime};charset=utf-8` });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = name;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

export function downloadArtifact(artifact: Artifact): void {
  downloadText(artifact.name, artifact.content, artifact.mime);
}
