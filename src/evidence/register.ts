/**
 * Evidence Register.
 *
 * Every quantitative claim used or considered by this application is stored here
 * with an explicit status. Source-reported values are kept separate from derived
 * and assumed values. Conflicting reports are preserved as conflicts and are never
 * silently reconciled. Unknown values are recorded as UNKNOWN and are never filled
 * in with a generic substitute.
 *
 * Quotes are short transcriptions from the identified source; where the primary
 * document could not be read, the record says so and the confidence is reduced.
 */

export type EvidenceStatus = "SOURCE_REPORTED" | "DERIVED" | "ASSUMED" | "CONFLICT" | "UNKNOWN";
export type Confidence = "HIGH" | "MEDIUM" | "LOW" | "NONE";

